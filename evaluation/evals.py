import os 
from langchain_ollama import ChatOllama
from langchain_core.prompts import PromptTemplate
from langchain_core.runnables import RunnablePassthrough
from langchain_core.output_parsers import JsonOutputParser

def run_evals(userquery, retrived_context, final_response):
    """
    Function to run evaluations on the final response generated by the LLM.
    Args:
        userquery: The input query for content generation.
        retrived_context: The context retrieved from the vectorstore.
        final_response: The final output generated by the LLM.
    Returns:
        The evaluation result as a string.
    """
    model = ChatOllama(
        model ="qwen3:0.6b",
        temperature= 0.5, 
        num_predict = 1000 ,
        disable_streaming = True
    )

    eval_template = (
    """You are an expert evaluator for the quality of responses generated by a botanical and home plant assistant.\n
        You are an independent Quality Assurance judge evaluating a Retrieval-Augmented Generation (RAG) system.
        Analyze the three inputs below and calculate three distinct metrics scored strictly between 0.0 (Worst) and 1.0 (Perfect).
        
        Inputs to evaluate:
        - User Query: {query}
        - Retrieved Context Chunks: {context}
        - System Generated Response: {response}
        
        Metrics to calculate:
        1. "context_relevance": Rate 1.0 if the context chunks contain explicit data necessary to resolve the query. Rate 0.0 if the context is entirely irrelevant fluff.
        2. "faithfulness": Rate 1.0 if every single statement in the generated response can be directly proven by the retrieved context chunks. Deduct points if the response extrapolates or hallucinates outside the text.
        3. "answer_relevance": Rate 1.0 if the response directly, cleanly answers what the user asked without missing details or rambling.
        
        Provide your output STRICTLY as a valid JSON object with the keys: "context_relevance", "faithfulness", "answer_relevance", and a brief 1-sentence "reasoning". Do not include markdown headers or conversational filler.
        """
    )

    prompt = PromptTemplate(
        template = eval_template, 
        input_variables = ["query", "context", "response"]

    )

    eval_chain = prompt | model | JsonOutputParser()

    evaluation_result = eval_chain.invoke({
        "query": userquery,
        "context": retrived_context,
        "response": final_response
    })
    
    return evaluation_result